/** Backend text in the current language (unknown text is returned unchanged). */
export function trBackend(text: string | null | undefined): string {
  if (!text) return text ?? "";
  if (current === "en") return text;
  for (const [re, f] of BACKEND_KO) {
    const m = text.match(re);
    if (m) return f(m);
  }
  return text;
}

interface LangCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: Key, vars?: Record<string, string | number>) => string;
}

const Ctx = createContext<LangCtx>({ lang: "en", setLang: () => undefined, t: tr });

export function LangProvider({ initial, children }: { initial: Lang; children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initial);
  current = lang;
  const setLang = useCallback((l: Lang) => {
    current = l;
    try {
      localStorage.setItem(LS_KEY, l);
    } catch {
      /* storage unavailable: choice lasts for this visit */
    }
    setLangState(l);
  }, []);
  // t is recreated on language change so components re-render with the new language
  const t = useCallback((key: Key, vars?: Record<string, string | number>) => tr(key, vars), [lang]); // eslint-disable-line react-hooks/exhaustive-deps
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useT(): LangCtx {
  return useContext(Ctx);
}
