const TABLES: Record<Lang, Record<Key, string>> = { en, ko };
const LS_KEY = "desk.lang";
let current: Lang = "en";

export function getLang(): Lang {
  return current;
}

export function storedLang(): Lang | null {
  try {
    const v = localStorage.getItem(LS_KEY);
    return v === "en" || v === "ko" ? v : null;
  } catch {
    return null;
  }
}

/** Translate outside React (format helpers). */
export function tr(key: Key, vars?: Record<string, string | number>): string {
  let s: string = TABLES[current][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

